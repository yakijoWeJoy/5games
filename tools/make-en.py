#!/usr/bin/env python3
"""
Builds en/index.html from index.html: the same game, but the page head that WhatsApp / Facebook /
Instagram read for the link preview is in English. Invites sent from an English phone link here.
Run after every change to index.html:   python3 tools/make-en.py        (--check: fail if out of date)
"""
import sys, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
src = (ROOT / 'index.html').read_text()

def swap(s, old, new):
    if old not in s:
        sys.exit(f'make-en: cannot find {old!r} in index.html')
    return s.replace(old, new, 1)

s = src
s = swap(s, '<html lang="he" dir="rtl">', '<html lang="en" dir="ltr">')
s = swap(s, '<head>\n', '<head>\n<!-- GENERATED by tools/make-en.py from index.html – do not edit by hand -->\n<base href="../">\n')
s = swap(s, '<title>דף ועיפרון</title>', '<title>Paper &amp; Pencil</title>')
s = swap(s, '<meta name="apple-mobile-web-app-title" content="דף ועיפרון">', '<meta name="apple-mobile-web-app-title" content="Paper &amp; Pencil">')
start = s.index('<meta name="description"'); end = s.index('\n', start)
s = s[:start] + '<meta name="description" content="Five pencil-and-paper games for two, each on your own phone: Bulls &amp; Cows, Hangman, Battleships, Dots &amp; Boxes and Five in a Row. Free, no sign-up.">' + s[end:]
for prop, val in [('og:title', 'Paper &amp; Pencil – 5 games for two'),
                  ('og:description', 'Bulls &amp; Cows · Hangman · Battleships · Dots &amp; Boxes · Five in a Row – each on your own phone. Come play with me!'),
                  ('og:image', 'https://small-joys.com/icons/og-en.png'),
                  ('og:url', 'https://small-joys.com/en/')]:
    start = s.index(f'<meta property="{prop}" content="'); end = s.index('\n', start)
    s = s[:start] + f'<meta property="{prop}" content="{val}">' + s[end:]

out = ROOT / 'en' / 'index.html'
if '--check' in sys.argv:
    ok = out.exists() and out.read_text() == s
    print('en/index.html is up to date' if ok else 'en/index.html is OUT OF DATE: run python3 tools/make-en.py')
    sys.exit(0 if ok else 1)
out.parent.mkdir(exist_ok=True)
out.write_text(s)
print('wrote en/index.html')
